//! Annex B Table 3-B.3 "Coefficients D[i] of the synthesis window"
//! (ISO/IEC 11172-3 (1993), full-PDF pages 50-52 — staged as the
//! renders
//! `docs/audio/mp3/annex-b-renders/Table-B.3-coefficients-Di-p56..58.png`
//! in this workspace).
//!
//! Clean-room: every value here is the literal Annex B PDF reading.
//! No third-party MP2 source was consulted; the 512 floating-point
//! values were transcribed from the staged PDF
//! `docs/audio/mp3/ISO_IEC_11172-3-MP3-1993.pdf` (SHA-256
//! `ef67bbc34eaab825e804bb87835c0cc0cd9ae6c7f77d3cec64d779726ffe322d`)
//! via `pdftotext -layout`, with the residual OCR artefacts resolved
//! by direct visual cross-check against the PNG renders. The PDF
//! introduction describes the coefficients as "derived by numerical
//! optimization".
//!
//! The §2.4.3.3.5 synthesis filterbank windows a 512-entry intermediate
//! vector `U` by these coefficients to produce a 512-entry `W`, after
//! which 32 PCM samples are produced as
//! `S_j = sum_{i = 0..16} W[j + 32 * i]`. See [`crate::synthesis`].
//!
//! ## Sign convention
//!
//! Unlike most published "MP1/MP2 window" tables, the spec's Table
//! 3-B.3 tabulates *signed* coefficients — the leading sign on each
//! entry is part of the value and is consumed verbatim by the
//! `W_i = U_i * D_i` step. The window has a complex sign pattern with
//! flips at indices 64, 128, 192, 256, 320, 384, and 448; the maximum
//! magnitude is `1.144989014` at index 256 (and symmetric drops to
//! `±1.144287109` at indices 255 and 257).
//!
//! ## Cross-checks
//!
//! - The table size is exactly 512.
//! - `D[0] == 0`.
//! - `D[256] == 1.144989014` (the global peak).
//! - `|D[442]| == |D[443]| == 0.003479004` (the secondary peak block,
//!   in the negative sign region).
//! - The table satisfies the documented anti-mirror identity
//!   `|D[256 + k]| == |D[256 - k]|` for `k != 0`, modulo the published
//!   sign blocks (a unit test pins this).

