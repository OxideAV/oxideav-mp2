//! Annex C Table C.1 "Coefficients C[i] of the analysis window"
//! (ISO/IEC 11172-3 (1993), §C.1.3, PDF pages 67-69 of the staged
//! `docs/audio/mp3/ISO_IEC_11172-3-MP3-1993.pdf`, SHA-256
//! `ef67bbc34eaab825e804bb87835c0cc0cd9ae6c7f77d3cec64d779726ffe322d`).
//!
//! Clean-room: every value here is a literal Annex C PDF reading. No
//! third-party MP2 source was consulted. The 512 9-digit floating-point
//! values were transcribed from the staged PDF via tesseract OCR on
//! 300-DPI `pdftoppm` renders of the source pages, with two
//! independent `pdftotext` extractions (`-layout` and `-raw`) used as
//! tie-breakers against OCR ambiguity around index-side punctuation
//! (`Cl 7]=` vs `cc 7]=`, `Cl 76}=` vs `C[ 761=`, `Cl408]=` vs
//! `C[40R]=`, etc.).
//!
//! The §C.1.3 analysis filterbank windows a 512-entry input sample
//! vector `X` by these coefficients to produce a 512-entry `Z`, before
//! the 64-entry partial-sum stage and the `S_i = sum_k M_ik Y_k`
//! matrixing step that yields 32 subband samples. See
//! [`crate::analysis`].
//!
//! ## Sign convention
//!
//! Unlike most published "MP1/MP2 window" tables, Annex C tabulates
//! *signed* coefficients — the leading sign on each entry is part of
//! the value and is consumed verbatim by the windowing step
//! `Z_i = C_i * X_i`. The window has the same complex sign pattern as
//! the synthesis-side Annex B Table 3-B.3, with sign flips at indices
//! 64, 128, 192, 256, 320, 384, and 448; the maximum magnitude is
//! `0.035780907` at index 256.
//!
//! ## Spec-paired invariant with Annex B Table 3-B.3
//!
//! Annex C Table C.1 and Annex B Table 3-B.3 are spec-paired filterbank
//! windows derived from the same prototype low-pass response. The pair
//! satisfies `D[i] == 32 * C[i]` to within the 9-decimal-digit rounding
//! both tables are quoted at (the factor of 32 absorbs the
//! critical-sampling rate change between the analysis-side
//! `f_s -> f_s/32` decimation and the synthesis-side
//! `f_s/32 -> f_s` interpolation). This identity is *cross-checked* by
//! the `c_matches_d_over_32_within_rounding` unit test but is *not*
//! used to derive `C[]` from `D[]` — both tables are transcribed
//! independently from their respective Annex sections.
//!
//! ## Cross-checks
//!
//! - The table size is exactly 512.
//! - `C[0] == 0`.
//! - `C[256] == 0.035780907` (the global peak).
//! - `|C[69]| == |C[70]| == 0.000108719` (the row-3 flat segment).
//! - `|C[442]| == |C[443]| == 0.000108719` (the symmetric counterpart
//!   in the negative sign region).
//! - The 7 sign-block boundaries at indices 64, 128, 192, 256, 320,
//!   384, 448 produce the documented sign flip between successive
//!   entries.
//! - For every `i`, `|C[i] - D[i] / 32.0| < 1e-9` (`D` being the
//!   `crate::tables_synthesis::D` Annex B Table 3-B.3 reading) — both
//!   transcriptions were performed independently from the same PDF and
//!   the spec-paired invariant is honored.

