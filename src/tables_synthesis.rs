#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn d_has_the_expected_size() {
        assert_eq!(D.len(), D_LEN);
        assert_eq!(D_LEN, 512);
    }

    #[test]
    fn known_pdf_endpoints_match() {
        // PDF reading: D[0] = 0,000000000.
        assert_eq!(D[0], 0.0);
        // PDF reading: D[69] = D[70] = 0,003479004 (first peak block).
        assert!((D[69] - 0.003_479_004).abs() < 1e-9);
        assert!((D[70] - 0.003_479_004).abs() < 1e-9);
        // PDF reading: D[256] = 1,144989014 (global peak).
        assert!((D[256] - 1.144_989_014).abs() < 1e-9);
        // PDF reading: D[442] = D[443] = -0,003479004 (mirror peak).
        assert!((D[442] - (-0.003_479_004)).abs() < 1e-9);
        assert!((D[443] - (-0.003_479_004)).abs() < 1e-9);
    }

    #[test]
    fn d_peak_magnitude_is_at_256() {
        let peak = D.iter().fold(0.0_f64, |a, &v| a.max(v.abs()));
        assert!((peak - 1.144_989_014).abs() < 1e-9);
        assert!((D[256].abs() - peak).abs() < 1e-12);
    }

    #[test]
    fn d_satisfies_anti_mirror_magnitude_identity() {
        // The published Annex B Table 3-B.3 has |D[256 + k]| == |D[256
        // - k]| for k != 0 (modulo the 8 documented sign-block flips).
        // We assert the magnitude identity directly: the symbol whose
        // index is mirrored about 256 carries the same magnitude.
        for k in 1..=255 {
            let lhs = D[256 + k].abs();
            let rhs = D[256 - k].abs();
            assert!(
                (lhs - rhs).abs() < 1e-9,
                "k={k}: |D[{}]| = {} vs |D[{}]| = {}",
                256 + k,
                lhs,
                256 - k,
                rhs
            );
        }
    }

    #[test]
    fn d_has_sign_block_boundaries_at_documented_indices() {
        // The PDF reading exhibits sign flips at indices 64, 128, 192,
        // 256, 320, 384, 448 (between successive 64-sample blocks).
        // Specifically D[63] is negative and D[64] is positive, etc.
        let boundaries = [64usize, 128, 192, 256, 320, 384, 448];
        for &b in &boundaries {
            assert!(
                D[b - 1].signum() != D[b].signum(),
                "expected sign flip between D[{}]={} and D[{}]={}",
                b - 1,
                D[b - 1],
                b,
                D[b]
            );
        }
    }
}
